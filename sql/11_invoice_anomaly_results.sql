USE ROLE ACCOUNTADMIN;
USE WAREHOUSE AP_AUTOPILOT_WH;
USE DATABASE AP_AUTOPILOT;
USE SCHEMA AP_AUTOPILOT.CORE;

CREATE OR REPLACE TABLE INVOICE_ANOMALY_RESULTS AS

SELECT

i.INVOICE_ID,

i.VENDOR_ID,

i.PO_ID,

p.PRICE_MISMATCH,

p.DIFFERENCE_PERCENT,

c.CONTRACT_STATUS,

CASE

WHEN c.CONTRACT_STATUS='EXPIRED'
THEN 'HIGH'

WHEN p.PRICE_MISMATCH
THEN 'HIGH'

ELSE 'LOW'

END AS SEVERITY,

CASE

WHEN c.CONTRACT_STATUS='EXPIRED'
THEN 'Invoice against expired contract'

WHEN p.PRICE_MISMATCH
THEN 'Contract price differs from PO'

ELSE 'No anomaly'

END AS EXPLANATION,

CURRENT_TIMESTAMP() DETECTED_AT

FROM AP_AUTOPILOT.CORE.INVOICES i

LEFT JOIN CONTRACT_PRICE_CHECK p

ON i.PO_ID=p.PO_ID

LEFT JOIN CONTRACT_STATUS c

ON i.VENDOR_ID=c.VENDOR_ID;