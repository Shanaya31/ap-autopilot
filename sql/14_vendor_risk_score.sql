CREATE OR REPLACE VIEW VENDOR_RISK_SCORE AS

SELECT

VENDOR_ID,

COUNT(*) AS TOTAL_INVOICES,

SUM(
CASE
WHEN SEVERITY='HIGH'
THEN 1
ELSE 0
END
) HIGH_RISK_COUNT,

ROUND(

100 *

SUM(
CASE
WHEN SEVERITY='HIGH'
THEN 1
ELSE 0
END
)

/

COUNT(*),

2

) AS RISK_PERCENT

FROM AP_AUTOPILOT.CORE.INVOICE_ANOMALY_RESULTS

GROUP BY VENDOR_ID

ORDER BY RISK_PERCENT DESC;