CREATE OR REPLACE VIEW AP_REVIEW_QUEUE AS

SELECT

i.INVOICE_ID,

i.VENDOR_ID,

a.SEVERITY,

a.EXPLANATION,

ca.RISK_LEVEL,

ca.RISK_REASON,

CASE

WHEN a.SEVERITY='HIGH'

THEN 'MANUAL REVIEW'

ELSE 'AUTO APPROVE'

END AS RECOMMENDED_ACTION

FROM INVOICE_ANOMALY_RESULTS a

JOIN CONTRACT_CLAUSE_ANALYSIS ca

USING(VENDOR_ID)

JOIN INVOICES i

USING(INVOICE_ID);