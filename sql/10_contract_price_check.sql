CREATE OR REPLACE VIEW CONTRACT_PRICE_CHECK AS

SELECT

po.PO_ID,

po.VENDOR_ID,

po.LINE_ITEM,

po.UNIT_PRICE AS PO_PRICE,

cp.CONTRACT_UNIT_PRICE,

ROUND(
cp.CONTRACT_UNIT_PRICE-po.UNIT_PRICE,
2
) AS PRICE_DIFFERENCE,

ROUND(

(
cp.CONTRACT_UNIT_PRICE-po.UNIT_PRICE
)

/

NULLIF(po.UNIT_PRICE,0)

*100,

2

) AS DIFFERENCE_PERCENT,

CASE

WHEN ABS(

(cp.CONTRACT_UNIT_PRICE-po.UNIT_PRICE)

/

NULLIF(po.UNIT_PRICE,0)

)>0.10

THEN TRUE

ELSE FALSE

END AS PRICE_MISMATCH

FROM PURCHASE_ORDERS po

JOIN CONTRACT_PRICING cp

ON po.VENDOR_ID=cp.VENDOR_ID

AND LOWER(po.LINE_ITEM)=LOWER(cp.LINE_ITEM);