USE ROLE ACCOUNTADMIN;
USE WAREHOUSE AP_AUTOPILOT_WH;
USE DATABASE AP_AUTOPILOT;
USE SCHEMA CORE;

CREATE OR REPLACE VIEW AP_REVIEW_QUEUE_UI AS

SELECT

ROW_NUMBER()
OVER(
ORDER BY
CASE SEVERITY

WHEN 'HIGH' THEN 1

WHEN 'MEDIUM' THEN 2

ELSE 3

END

) AS PRIORITY,

*

FROM AP_AUTOPILOT.CORE.AP_REVIEW_QUEUE;